"""Writes swift/Sources/HealthGraph/Cypher.swift from the Python sources.

The Cypher the Swift library runs is the Python reference's, verbatim:
schema.cypher, omop.cypher, the statements in store.py and the named queries
in queries.py. CypherParityTests in the Swift package fails if they drift.

    python3 scripts/gen_swift_cypher.py            # write it
    python3 scripts/gen_swift_cypher.py --check    # exit 1 when it is stale
"""
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from health_graph import knowledge, store  # noqa: E402
from health_graph.queries import QUERIES  # noqa: E402

OUT = ROOT / "swift/Sources/HealthGraph/Cypher.swift"
KNOWLEDGE_OUT = ROOT / "swift/Sources/HealthGraph/KnowledgeData.swift"

# Swift name -> knowledge.py constant: the knowledge layer's seed.
KNOWLEDGE = [
    ("seedRisks", "SEED_RISKS"),
    ("seedScores", "SEED_SCORES"),
    ("seedMarkers", "SEED_MARKERS"),
    ("seedPruneRanges", "SEED_PRUNE_RANGES"),
    ("seedRanges", "SEED_RANGES"),
    ("seedRangeSources", "SEED_RANGE_SOURCES"),
    ("seedStudies", "SEED_STUDIES"),
    ("seedStudyMarkers", "SEED_STUDY_MARKERS"),
    ("seedStudyScores", "SEED_STUDY_SCORES"),
    ("seedRiskLinks", "SEED_RISK_LINKS"),
    ("seedVersion", "SEED_VERSION"),
]

# Swift name -> store.py constant, in the order they run.
STATEMENTS = [
    ("deleteReport", "DELETE_REPORT"),
    ("upsertReport", "UPSERT_REPORT"),
    ("upsertObservations", "UPSERT_OBSERVATIONS"),
    ("unlinkSameMeasurements", "UNLINK_SAME_MEASUREMENTS"),
    ("linkSameMeasurements", "LINK_SAME_MEASUREMENTS"),
    ("replaceWearables", "REPLACE_WEARABLES"),
    ("upsertWearables", "UPSERT_WEARABLES"),
]


def raw(text: str, indent: int) -> str:
    """A Swift raw multi-line string literal holding `text`."""
    pad = " " * indent
    body = "\n".join((pad + line) if line.strip() else "" for line in text.splitlines())
    return f'#"""\n{body}\n{pad}"""#'


def swift_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    out = [
        "// Generated by scripts/gen_swift_cypher.py from health_graph/{schema,omop}.cypher,",
        "// store.py and queries.py. Do not edit: change the Python and run the script.",
        "// The parity test (CypherParityTests) fails if the two drift apart.",
        "// swiftlint:disable line_length",
        "",
        "enum Cypher {",
        f"  static let schema = {raw((ROOT / 'health_graph/schema.cypher').read_text().rstrip(), 2)}",
        "",
        f"  static let omop = {raw((ROOT / 'health_graph/omop.cypher').read_text().rstrip(), 2)}",
    ]
    for swift, py in STATEMENTS:
        text = textwrap.dedent(getattr(store, py)).strip()
        out += ["", f"  static let {swift} = {raw(text, 2)}"]
    for swift, py in KNOWLEDGE:
        text = textwrap.dedent(getattr(knowledge, py)).strip()
        out += ["", f"  static let {swift} = {raw(text, 2)}"]
    out += [
        "}",
        "",
        "/// Named read-only queries (CLI, tests, the app). Same as health_graph/queries.py.",
        "public enum Queries {",
        "  public static let all: [String: (description: String, cypher: String)] = [",
    ]
    for name, (description, cypher) in QUERIES.items():
        out += [
            f"    {swift_string(name)}: (",
            f"      {swift_string(description)},",
            f"      {raw(textwrap.dedent(cypher).strip(), 6)}),",
        ]
    out += ["  ]", "}", ""]
    return "\n".join(out)


def render_knowledge() -> str:
    """The knowledge layer's facts (risks, scores, markers, ranges, studies, risk links) as JSON in Swift."""
    import json
    data = {
        "risks": knowledge.HEALTH_RISKS,
        "scores": knowledge.RISK_SCORES,
        "markers": knowledge._marker_rows(),
        "ranges": knowledge._range_rows(),
        "rangeIds": [r["id"] for r in knowledge._range_rows()],
        "rangeSources": knowledge._range_source_rows(),
        "studies": knowledge._study_rows(),
        "examines": knowledge._examines_rows(),
        "informs": knowledge._informs_rows(),
        "links": knowledge.RISK_LINKS,
    }
    source = json.loads((ROOT / "health_graph/reference_ranges.json").read_text())["source"]
    blob = json.dumps(data, ensure_ascii=False, sort_keys=True, indent=1)
    return "\n".join([
        "// Generated by scripts/gen_swift_cypher.py from health_graph/knowledge.py and",
        "// reference_ranges.json. Do not edit: change the Python and run the script.",
        "// swiftlint:disable line_length",
        "",
        "enum KnowledgeData {",
        f"  static let fingerprint = {swift_string(knowledge.fingerprint())}",
        f"  static let rangesSource = {swift_string(source)}",
        f"  static let json = {raw(blob, 2)}",
        "}",
        "",
    ])


if __name__ == "__main__":
    outputs = [(OUT, render()), (KNOWLEDGE_OUT, render_knowledge())]
    if "--check" in sys.argv:
        stale = [o for o, text in outputs if not o.exists() or o.read_text() != text]
        for o in stale:
            print(f"{o.relative_to(ROOT)} is stale: run python3 scripts/gen_swift_cypher.py")
        if stale:
            sys.exit(1)
        print("Cypher.swift and KnowledgeData.swift are current")
    else:
        for o, text in outputs:
            o.write_text(text)
            print(f"wrote {o.relative_to(ROOT)}")
