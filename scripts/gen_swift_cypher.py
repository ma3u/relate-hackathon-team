"""Writes swift/Sources/HealthGraph/Cypher.swift from the Python sources.

The Cypher the Swift library runs is the Python reference's, verbatim:
schema.cypher, omop.cypher, the statements in store.py and the named queries
in queries.py. CypherParityTests in the Swift package fails if they drift.

    python3 scripts/gen_swift_cypher.py            # write it
    python3 scripts/gen_swift_cypher.py --check    # exit 1 when it is stale
"""
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from health_graph import store  # noqa: E402
from health_graph.queries import QUERIES  # noqa: E402

OUT = ROOT / "swift/Sources/HealthGraph/Cypher.swift"

# Swift name -> store.py constant, in the order they run.
STATEMENTS = [
    ("deleteReport", "DELETE_REPORT"),
    ("upsertReport", "UPSERT_REPORT"),
    ("upsertObservations", "UPSERT_OBSERVATIONS"),
    ("unlinkSameMeasurements", "UNLINK_SAME_MEASUREMENTS"),
    ("linkSameMeasurements", "LINK_SAME_MEASUREMENTS"),
    ("replaceWearables", "REPLACE_WEARABLES"),
    ("upsertWearables", "UPSERT_WEARABLES"),
]


def raw(text: str, indent: int) -> str:
    """A Swift raw multi-line string literal holding `text`."""
    pad = " " * indent
    body = "\n".join((pad + line) if line.strip() else "" for line in text.splitlines())
    return f'#"""\n{body}\n{pad}"""#'


def swift_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    out = [
        "// Generated by scripts/gen_swift_cypher.py from health_graph/{schema,omop}.cypher,",
        "// store.py and queries.py. Do not edit: change the Python and run the script.",
        "// The parity test (CypherParityTests) fails if the two drift apart.",
        "// swiftlint:disable line_length",
        "",
        "enum Cypher {",
        f"  static let schema = {raw((ROOT / 'health_graph/schema.cypher').read_text().rstrip(), 2)}",
        "",
        f"  static let omop = {raw((ROOT / 'health_graph/omop.cypher').read_text().rstrip(), 2)}",
    ]
    for swift, py in STATEMENTS:
        text = textwrap.dedent(getattr(store, py)).strip()
        out += ["", f"  static let {swift} = {raw(text, 2)}"]
    out += [
        "}",
        "",
        "/// Named read-only queries (CLI, tests, the app). Same as health_graph/queries.py.",
        "public enum Queries {",
        "  public static let all: [String: (description: String, cypher: String)] = [",
    ]
    for name, (description, cypher) in QUERIES.items():
        out += [
            f"    {swift_string(name)}: (",
            f"      {swift_string(description)},",
            f"      {raw(textwrap.dedent(cypher).strip(), 6)}),",
        ]
    out += ["  ]", "}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 scripts/gen_swift_cypher.py")
            sys.exit(1)
        print("Cypher.swift is current")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
