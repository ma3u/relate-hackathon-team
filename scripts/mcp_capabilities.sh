#!/usr/bin/env bash
# Lists what the Klarbefund for Mac MCP server (klarbefund-mcp) offers, with the
# official MCP Inspector in CLI mode, and writes it into docs/MCP.md between
# <!-- generated:start --> and <!-- generated:end -->.
#
#   scripts/mcp_capabilities.sh                  # the newest built helper in DerivedData or apps/mac/.build
#   scripts/mcp_capabilities.sh path/to/klarbefund-mcp
#   scripts/mcp_capabilities.sh --check          # fail if docs/MCP.md is not current
#
# Only discovery and list methods: server/discover, tools/list, prompts/list,
# resources/list. It never calls a tool, so it never reads the health graph,
# whether or not Klarbefund for Mac is open.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DOC="$REPO/docs/MCP.md"
# Pinned: an Inspector release at least two weeks old when chosen (2.13.0,
# Oct 28, 2026), with --cli and --protocol-era. Bump it deliberately.
INSPECTOR_VERSION="2.13.0"
INSPECTOR="@modelcontextprotocol/inspector@$INSPECTOR_VERSION"

log() { echo "mcp-capabilities: $*" >&2; }

CHECK=0
if [[ "${1:-}" == "--check" ]]; then CHECK=1; shift; fi

find_helper() {
  local candidates=()
  local dd="$HOME/Library/Developer/Xcode/DerivedData"
  shopt -s nullglob
  candidates+=("$dd"/Klarbefund-*/Build/Products/Debug/Klarbefund.app/Contents/Helpers/klarbefund-mcp)
  candidates+=("$dd"/Klarbefund-*/Build/Products/Debug/klarbefund-mcp)
  candidates+=("$REPO"/apps/mac/.build/Build/Products/Debug/Klarbefund.app/Contents/Helpers/klarbefund-mcp)
  candidates+=("$REPO"/apps/mac/.build/Build/Products/Debug/klarbefund-mcp)
  shopt -u nullglob
  local best="" newest=0 t
  for c in "${candidates[@]}"; do
    [[ -x "$c" ]] || continue
    t=$(stat -f %m "$c")
    if ((t > newest)); then newest=$t; best=$c; fi
  done
  [[ -n "$best" ]] || return 1
  echo "$best"
}

HELPER="${1:-}"
if [[ -z "$HELPER" ]]; then
  HELPER="$(find_helper)" || {
    log "no built klarbefund-mcp found; build it first: cd apps/mac && xcodegen generate && xcodebuild -scheme Klarbefund build"
    exit 1
  }
fi
[[ -x "$HELPER" ]] || { log "not an executable: $HELPER"; exit 1; }
command -v npx >/dev/null || { log "npx not found (Node.js 22.19 or newer)"; exit 1; }
log "helper: $HELPER"
log "inspector: $INSPECTOR"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/mcp-capabilities.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
# The Inspector keeps a server catalog; keep it out of the home folder.
export MCP_CATALOG_PATH="$WORK/inspector-catalog.json"

inspect() { # era method
  (cd "$WORK" && npx -y "$INSPECTOR" --cli --format json -q --protocol-era "$1" --method "$2" "$HELPER") \
    > "$WORK/$1-${2//\//_}.json"
}

for method in tools/list prompts/list resources/list; do
  log "$method (legacy: initialize)"
  inspect legacy "$method"
done
log "prompts/list (modern: 2026-07-28)"
inspect modern prompts/list

# server/discover straight over stdio: the revisions and capabilities.
printf '%s\n' '{"jsonrpc":"2.0","id":1,"method":"server/discover","params":{"_meta":{"io.modelcontextprotocol/protocolVersion":"2026-07-28","io.modelcontextprotocol/clientCapabilities":{}}}}' \
  | "$HELPER" > "$WORK/discover.json"

python3 -I - "$WORK" "$DOC" "$INSPECTOR_VERSION" "$CHECK" <<'PY'
import json
import pathlib
import sys

work, doc, version, check = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3], sys.argv[4] == "1"


def load(name):
    data = json.loads((work / name).read_text())
    if "error" in data:
        sys.exit(f"mcp-capabilities: {name}: {data['error']}")
    return data["result"]


def cell(s):
    return " ".join(str(s).split()).replace("|", "\\|")


tools = load("legacy-tools_list.json")["tools"]
prompts = load("legacy-prompts_list.json")["prompts"]
resources = load("legacy-resources_list.json")["resources"]
modern = load("modern-prompts_list.json")["prompts"]
discover = load("discover.json")
if [p["name"] for p in modern] != [p["name"] for p in prompts]:
    sys.exit("mcp-capabilities: the 2026-07-28 and legacy prompt lists differ")

caps = ", ".join(sorted(discover["capabilities"]))
out = [
    f"Generated by `scripts/mcp_capabilities.sh` with the MCP Inspector {version} (`--cli`) against the built "
    "`klarbefund-mcp`: the lists below are what a client receives. Do not edit by hand.",
    "",
    f"- **Server:** {discover['_meta']['io.modelcontextprotocol/serverInfo']['name']}",
    "- **Revisions** (`server/discover`): " + ", ".join(f"`{v}`" for v in discover["supportedVersions"]),
    f"- **Capabilities:** {caps}",
    f"- **Counts:** {len(tools)} tools, {len(prompts)} prompts, {len(resources)} resources "
    "(the same prompt list through `initialize` and through 2026-07-28)",
    "",
    "### Tools",
    "",
    "| Tool | Title | Annotations | Description |",
    "| --- | --- | --- | --- |",
]
for t in tools:
    ann = ", ".join(f"{k}: {str(v).lower()}" for k, v in t.get("annotations", {}).items())
    out.append(f"| `{t['name']}` | {cell(t.get('title', ''))} | {ann} | {cell(t.get('description', ''))} |")
out += ["", "### Prompts", "", "| Prompt | Title | Arguments | Description |", "| --- | --- | --- | --- |"]
for p in prompts:
    args = ", ".join(f"`{a['name']}`" + ("" if a.get("required") else " (optional)") for a in p.get("arguments", []))
    out.append(f"| `{p['name']}` | {cell(p.get('title', ''))} | {args or '–'} | {cell(p.get('description', ''))} |")
out += ["", "### Resources (guides)", "", "| URI | Title | Type | Description |", "| --- | --- | --- | --- |"]
for r in resources:
    out.append(f"| `{r['uri']}` | {cell(r.get('title', r['name']))} | {r.get('mimeType', '')} | "
               f"{cell(r.get('description', ''))} |")
generated = "\n".join(out)

text = doc.read_text()
start, end = "<!-- generated:start -->", "<!-- generated:end -->"
if start not in text or end not in text:
    sys.exit(f"mcp-capabilities: {doc} lacks the {start} / {end} markers")
head, rest = text.split(start, 1)
_, tail = rest.split(end, 1)
new = f"{head}{start}\n{generated}\n{end}{tail}"
if check:
    if new != text:
        sys.exit("mcp-capabilities: docs/MCP.md is not current; run scripts/mcp_capabilities.sh")
    print("mcp-capabilities: docs/MCP.md is current")
elif new != text:
    doc.write_text(new)
    print(f"mcp-capabilities: wrote {len(tools)} tools, {len(prompts)} prompts, {len(resources)} resources to {doc}")
else:
    print("mcp-capabilities: docs/MCP.md already current")
PY
